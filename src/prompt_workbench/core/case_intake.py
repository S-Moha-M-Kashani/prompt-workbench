"""Turning a free-text description into something that can be run.

Two steps, deliberately separate. The task type is proposed by keyword against
the description, which costs nothing and is wrong often enough that it is always
overridable. The test cases are generated by a model, because writing eight
genuinely different inputs is real work and the thing most likely to be skipped
if it is left to the user — and a prompt with no cases cannot be measured at all.
"""

from collections.abc import Callable, Sequence
from datetime import datetime

from prompt_workbench.core.generation import GenerationError, as_text_tuple, parse_json_object
from prompt_workbench.core.prompt_registry import load_system_prompt
from prompt_workbench.models.case import CaseBrief, EvalCase
from prompt_workbench.models.identifiers import IdFactory
from prompt_workbench.models.model_settings import ModelSettings
from prompt_workbench.models.protocols import CompletionFn
from prompt_workbench.models.task_type import TaskType

DEFAULT_CASE_COUNT = 8


def generate_cases(
    *,
    description: str,
    task: TaskType,
    count: int,
    complete: CompletionFn,
    model: str,
    settings: ModelSettings | None,
    new_id: IdFactory,
) -> tuple[EvalCase, ...]:
    """Ask for ``count`` test cases for this description and job type."""
    if not description.strip():
        raise GenerationError("Describe what the prompt must do first.")

    request = (
        f"Write {count} test cases.\n\n"
        f"KIND OF JOB\n{task.label}: {task.description}\n\n"
        f"WHAT THE PROMPT MUST DO\n{description.strip()}"
    )
    raw = complete(
        [
            {"role": "system", "content": load_system_prompt("case_writer")},
            {"role": "user", "content": request},
        ],
        model=model,
        settings=settings,
    )
    payload = parse_json_object(raw, what="generated test cases")

    entries = payload.get("cases")
    if not isinstance(entries, list) or not entries:
        raise GenerationError(
            "The model returned no test cases. Try again, or write one by hand."
        )

    cases: list[EvalCase] = []
    for position, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            raise GenerationError(f"Generated case {position} was not an object")
        expected = entry.get("expected_output")
        try:
            cases.append(
                EvalCase(
                    id=new_id("case"),
                    input=str(entry.get("input", "")),
                    expected_output=str(expected).strip() if expected else None,
                    context=as_text_tuple(entry.get("context")),
                    retrieval_context=as_text_tuple(entry.get("retrieval_context")),
                    notes=str(entry.get("notes", "")).strip(),
                )
            )
        except ValueError as error:
            raise GenerationError(f"Generated case {position} is unusable: {error}") from error
    return tuple(cases)


def build_brief(
    *,
    description: str,
    task: TaskType,
    cases: Sequence[EvalCase],
    clock: Callable[[], datetime],
    output_format: str = "",
    notes: str = "",
) -> CaseBrief:
    """Assemble what the user has decided so far into one value."""
    return CaseBrief(
        description=description.strip(),
        task_type_key=task.key,
        created_at=clock(),
        cases=tuple(cases),
        output_format=output_format,
        notes=notes,
    )
